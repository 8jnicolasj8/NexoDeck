// Deterministic protocol v2 vectors shared by the C# server and the Android app.
// Run: node tools/generate-v2-vectors.mjs > docs/protocol-v2-vectors.json
import { createHmac, hkdfSync } from 'crypto';
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const b64url = (buffer) => Buffer.from(buffer).toString('base64url');

const pairSecret = b64url(Buffer.from('00112233445566778899aabbccddeeff', 'hex'));
const serverId = '3f1c2b4a-9d8e-4c7b-8a61-2f5e0d9c1b77';
const deviceId = 'dev_5f2c9a71b3';
const nonceC = b64url(Buffer.from('c0ffee000102030405060708090a0b0c', 'hex'));
const nonceS = b64url(Buffer.from('decafbad0f1e2d3c4b5a69788796a5b4', 'hex'));

const hmac = (key, text) => createHmac('sha256', key).update(text, 'utf8').digest();

const pairProof = b64url(hmac(Buffer.from(pairSecret, 'base64url'), `pair|${serverId}|${deviceId}|${nonceC}`));
const deviceKey = Buffer.from(
  hkdfSync('sha256', Buffer.from(pairSecret, 'base64url'), Buffer.from(deviceId, 'utf8'), Buffer.from(`vexadeck-device-key|${serverId}|${nonceC}|${nonceS}`, 'utf8'), 32)
);
const deviceKeyB64 = b64url(deviceKey);
const authProof = b64url(hmac(deviceKey, `auth|${serverId}|${nonceS}|${nonceC}`));
const sessionKey = hmac(deviceKey, `sess|${serverId}|${nonceS}|${nonceC}`);
const sessionKeyB64 = b64url(sessionKey);

const payload = '{"v":2,"t":"ping","id":null,"d":{"ts":1}}';
const envelopeMac = b64url(hmac(sessionKey, `s2c|1|${payload}`).subarray(0, 16));
const secondPayload = '{"v":2,"t":"welcome","id":null,"d":{"configRevision":3}}';
const secondMac = b64url(hmac(sessionKey, `s2c|2|${secondPayload}`).subarray(0, 16));

const vectors = {
  note: 'Generated by tools/generate-v2-vectors.mjs. Do not edit by hand.',
  pairSecret,
  serverId,
  deviceId,
  nonceC,
  nonceS,
  expected: {
    pairProof,
    deviceKey: deviceKeyB64,
    authProof,
    sessionKey: sessionKeyB64,
    envelopes: [
      { direction: 's2c', counter: 1, payload, mac: envelopeMac },
      { direction: 's2c', counter: 2, payload: secondPayload, mac: secondMac },
    ],
  },
};

const output = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'protocol-v2-vectors.json');
writeFileSync(output, JSON.stringify(vectors, null, 2) + '\n', 'utf8');
console.log(`Wrote ${output}`);
